"""OpenAPI (Swagger) configuration helpers."""


def only_versioned_paths(endpoints, **kwargs):
    """The app serves the same API at /api/ and /api/v1/; document the versioned public paths once."""
    return [e for e in endpoints if e[0].startswith("/api/v1/")]


DESCRIPTION = """
Brightloop runs subscriptions end to end: catalog, quotes, subscriptions, automatic GST invoicing, discounts,
payments, reports, data checks and an audit log.

## Authentication
- **Web users:** `POST /api/v1/auth/login` returns a token. Send it as `Authorization: Token <token>`.
- **Other systems:** an admin creates an API key on *Settings → API keys*. Send `X-API-Key: <key>`.
  Keys are scoped `read` and/or `write`, can be revoked, and are rate limited (120 requests/min by default).

Use **Authorize** above to try requests from this page; the authorization is remembered while the tab is open.

## Conventions
- Lists are paginated: `?page=2&page_size=50` (max 200) and return `{count, next, previous, results}`.
- Most lists accept `?search=` and the filters named in each operation.
- Money values are strings with two decimals (`"1234.50"`), currency INR.
- Errors: `{"detail": "..."}` or `{"field": ["message"]}` with status 400, 401, 403 or 404.
- **Idempotency:** send `Idempotency-Key: <unique id>` with any POST made with an API key; a retry with the same key
  returns the first response instead of doing the work twice.

## Roles
Admin: everything. Staff: day-to-day work, catalog read-only. Customer: only their own subscriptions and invoices.
"""

